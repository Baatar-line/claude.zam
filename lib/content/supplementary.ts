/**
 * Broad, deliberately gentle bands. No band reads as a verdict — a student
 * this test serves is 13 to 18, and a number here is self-reported and
 * unverifiable besides.
 */
export function iqBandFor(score: number): IqBand {
  if (score < 85) {
    return {
      labelMn: "Дундажаас доогуур хүрээ",
      noteMn:
        "Энэ тоо мэргэжлийн тохиролд ямар ч байдлаар нөлөөлөөгүй болохыг анхаараарай — дээрх үр дүн зөвхөн чиний хариултаас гардаг.",
    };
  }
  if (score < 115) {
    return {
      labelMn: "Дундаж хүрээ",
      noteMn: "Ихэнх хүний оноо энэ хүрээнд ордог.",
    };
  }
  if (score < 130) {
    return {
      labelMn: "Дундажаас өндөр хүрээ",
      noteMn: "Энэ тоо ганцаараа ямар мэргэжилд тохирохыг шийддэггүй — сонирхол, зан төлөв, үнэт зүйл адилхан чухал.",
    };
  }
  return {
    labelMn: "Маш өндөр хүрээ",
    noteMn: "Энэ тоо ганцаараа ямар мэргэжилд тохирохыг шийддэггүй — сонирхол, зан төлөв, үнэт зүйл адилхан чухал.",
  };
}

